/// <summary>
/// 적이 "지금 공격을 커밋(텔레그래프~타격 실행)하고 있는가"를 노출하는 계약 — 타이밍-크리티컬 프로토.
///
/// ★읽고-베기 코어 동사: 플레이어가 *커밋 중인 적*을 베면 크리티컬(공격 타이밍 듀얼, 방어 패링 ❌).
///   무기(KatanaWeapon)가 적중 시 GetComponentInParent로 이 계약을 찾아 크리티컬 여부를 판정한다.
///   종마다 새 무기 코드 0(OCP): 새 적이 이 인터페이스만 구현하면 자동으로 듀얼 대상이 된다.
///
/// "커밋"의 정의는 종이 소유한다(애니 상태머신이 진실) — 보통 윈드업(응축)~발사 구간. 접근·휴지·플린치는 비커밋.
/// ★구현 주의(L-1): 애니 상태로 판정하는 구현은 보통 레이어 0만 본다 — 멀티레이어 컨트롤러 종은 해당 레이어를 봐야 한다.
/// </summary>
public interface IAttackCommit
{
    /// <summary>지금 공격을 커밋(텔레그래프/윈드업~타격 실행) 중인가. 접근·휴지·플린치(GetHit)·Idle이면 false. (윈드업 글로우 등 넓은 신호용)</summary>
    bool IsCommittingAttack { get; }

    /// <summary>지금 *실제 타격을 실행* 중인가(돌진·물기 = 발사 구간). 윈드업(응축)·접근은 false.
    /// ★맞받음(클래시) 판정용 — "달려드는 그 타격 순간을 만난다"의 좁은 창. 커밋 전체가 아니라 타격 실행만.</summary>
    bool IsStriking { get; }
}
